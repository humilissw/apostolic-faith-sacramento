import os
import uuid
from pathlib import Path
from typing import Any

from fastapi import APIRouter, File, HTTPException, UploadFile, status
from fastapi.responses import FileResponse

from app.api.deps import SessionDep, require_scope
from app.config import settings
from app.models import Message
from app.repositories.event_repo import EventRepository
from app.requests.event_request import EventBulkDelete, EventCreate, EventUpdate
from app.responses.event_response import EventPublic, EventsPublic

router = APIRouter(prefix="/events", tags=["events"])

# Allowed flyer content types -> file extension
FLYER_CONTENT_TYPES: dict[str, str] = {
    "image/jpeg": ".jpg",
    "image/png": ".png",
    "image/webp": ".webp",
    "image/gif": ".gif",
}

MAX_FLYER_BYTES = 10 * 1024 * 1024


def _flyer_dir() -> Path:
    flyer_dir = Path(settings.EVENT_FLYER_DIR)
    if not flyer_dir.is_absolute():
        # Resolve relative paths against the backend root (src/be), independent of cwd.
        flyer_dir = Path(__file__).resolve().parents[3] / settings.EVENT_FLYER_DIR
    return flyer_dir


def _flyer_public_url(event_id: str) -> str:
    return f"{settings.API_V1_STR}/events/{event_id}/flyer"


def _to_public(event: Any) -> EventPublic:
    return EventPublic(
        id=event.id,
        title=event.title,
        description=event.description,
        date=event.date,
        start_time=event.start_time,
        end_time=event.end_time,
        created_on=event.created_on,
        updated_on=event.updated_on,
        flyer_url=_flyer_public_url(event.id) if event.flyer_path else None,
    )


@router.get("/liveness")
async def get_liveness() -> str:
    """Health check for liveness probe."""
    return "Live"


@router.get("/readiness")
async def get_readiness() -> str:
    """Health check for readiness probe."""
    return "Ready"


@router.get(
    "/",
    response_model=EventsPublic,
)
async def read_events(session: SessionDep, skip: int = 0, limit: int = 100) -> Any:
    """
    Retrieve all event entries.

    Returns a list of all event entries with pagination.
    Public endpoint — used by the public events page.
    """
    repository = EventRepository(session=session)
    events, total_count = await repository.get_all(skip=skip, limit=limit)

    return EventsPublic(data=[_to_public(i) for i in events], count=total_count)


@router.get(
    "/{event_id}",
    response_model=EventPublic,
)
async def read_event_by_id(event_id: str, session: SessionDep) -> Any:
    """
    Get event by ID.

    Returns a single event entry by its ID.
    Public endpoint — used by the public events page.
    """
    repository = EventRepository(session=session)
    event = await repository.get_by_id(event_id=event_id)
    if not event:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="Event not found",
        )

    return _to_public(event)


@router.get("/{event_id}/flyer")
async def read_event_flyer(event_id: str, session: SessionDep) -> Any:
    """
    Get the flyer image for an event.

    Public endpoint — the public events page and homepage display flyers
    without authentication.
    """
    repository = EventRepository(session=session)
    event = await repository.get_by_id(event_id=event_id)
    if not event or not event.flyer_path:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="Flyer not found",
        )

    # The stored filename is generated by us (uuid-based); guard anyway against
    # path traversal before joining it to the flyer directory.
    safe_name = os.path.basename(event.flyer_path)
    flyer_file = _flyer_dir() / safe_name
    if not flyer_file.is_file():
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="Flyer not found",
        )

    media_type, _ext = next(
        ((ct, ext) for ct, ext in FLYER_CONTENT_TYPES.items() if safe_name.endswith(ext)),
        ("application/octet-stream", ""),
    )
    return FileResponse(flyer_file, media_type=media_type)


