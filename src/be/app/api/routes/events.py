@router.post(
    "/{event_id}/flyer",
    response_model=EventPublic,
    dependencies=[require_scope("events:admin")],
)
async def upload_event_flyer_endpoint(
    *,
    session: SessionDep,
    event_id: str,
    file: UploadFile = File(...),
) -> Any:
    """
    Upload (or replace) the flyer image for an event.

    The flyer is displayed on the public events page and, for the next
    upcoming event, on the homepage.
    """
    content_type = file.content_type or ""
    if content_type not in FLYER_CONTENT_TYPES:
        raise HTTPException(
            status_code=status.HTTP_415_UNSUPPORTED_MEDIA_TYPE,
            detail="Flyer must be a JPEG, PNG, WebP, or GIF image",
        )

    payload = await file.read()
    if len(payload) > MAX_FLYER_BYTES:
        raise HTTPException(
            status_code=status.HTTP_413_REQUEST_ENTITY_TOO_LARGE,
            detail="Flyer image exceeds the 10 MB limit",
        )

    repository = EventRepository(session=session)
    event = await repository.get_by_id(event_id=event_id)
    if not event:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="Event not found",
        )

    flyer_dir = _flyer_dir()
    flyer_dir.mkdir(parents=True, exist_ok=True)

    previous_name = event.flyer_path
    stored_name = f"{event.id}-{uuid.uuid4().hex}{FLYER_CONTENT_TYPES[content_type]}"
    (flyer_dir / stored_name).write_bytes(payload)

    event = await repository.set_flyer(db_event=event, flyer_filename=stored_name)

    # Remove the superseded flyer file best-effort.
    if previous_name:
        try:
            old_file = flyer_dir / os.path.basename(previous_name)
            if old_file.is_file():
                old_file.unlink()
        except OSError:
            pass

    return _to_public(event)


@router.delete(
    "/{event_id}/flyer",
    response_model=Message,
    dependencies=[require_scope("events:admin")],
)
async def delete_event_flyer_endpoint(event_id: str, session: SessionDep) -> Any:
    """
    Remove the flyer image for an event.
    """
    repository = EventRepository(session=session)
    event = await repository.get_by_id(event_id=event_id)
    if not event:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="Event not found",
        )

    if event.flyer_path:
        flyer_file = _flyer_dir() / os.path.basename(event.flyer_path)
        await repository.set_flyer(db_event=event, flyer_filename=None)
        try:
            if flyer_file.is_file():
                flyer_file.unlink()
        except OSError:
            pass

    return Message(message="Flyer deleted successfully")


@router.patch(
    "/{event_id}",
    response_model=EventPublic,
    dependencies=[require_scope("events:admin")],
)
async def update_event_endpoint(
    *,
    session: SessionDep,
    event_id: str,
    event_in: EventUpdate,
) -> Any:
    """
    Update an event entry.

    Updates an existing event entry by ID.
    """
    repository = EventRepository(session=session)
    event = await repository.get_by_id(event_id=event_id)
    if not event:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="Event not found",
        )

    event = await repository.update(db_event=event, event_in=event_in)
    return _to_public(event)


def _remove_flyer_file(flyer_path: str | None) -> None:
    """Best-effort removal of a stored flyer file."""
    if not flyer_path:
        return
    try:
        flyer_file = _flyer_dir() / os.path.basename(flyer_path)
        if flyer_file.is_file():
            flyer_file.unlink()
    except OSError:
        pass


@router.delete(
    "/bulk",
    response_model=Message,
    dependencies=[require_scope("events:admin")],
)
async def bulk_delete_events_endpoint(session: SessionDep, bulk_in: EventBulkDelete) -> Any:
    """
    Delete multiple event entries.

    Deletes every event whose id appears in the request body. Ids that do not
    exist are ignored; returns how many events were actually deleted.
    """
    repository = EventRepository(session=session)
    events = await repository.get_many_by_ids(event_ids=list(dict.fromkeys(bulk_in.event_ids)))

    for event in events:
        _remove_flyer_file(event.flyer_path)

    await repository.delete_many(db_events=events)
    return Message(
        message=f"Deleted {len(events)} event{'s' if len(events) != 1 else ''} successfully"
    )


@router.delete(
    "/{event_id}",
    response_model=Message,
    dependencies=[require_scope("events:admin")],
)
async def delete_event_endpoint(event_id: str, session: SessionDep) -> Any:
    """
    Delete an event entry.

    Deletes an event entry by ID.
    """
    repository = EventRepository(session=session)
    event = await repository.get_by_id(event_id=event_id)
    if not event:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="Event not found",
        )

    _remove_flyer_file(event.flyer_path)

    await repository.delete(db_event=event)
    return Message(message="Event deleted successfully")
